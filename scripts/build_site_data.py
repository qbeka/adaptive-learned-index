#!/usr/bin/env python3
"""Writes site/results.js from recorded results, so the page can show nothing else.

Usage: scripts/build_site_data.py

Anything without a recorded source stays absent, and the page hides it.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def read_json(relative: str):
    path = ROOT / relative
    return json.loads(path.read_text()) if path.exists() else None


def oracle_operations() -> int:
    """Sums the operations the correctness suite checked in this build."""
    total = 0
    for test in ("test_reference", "test_static", "test_dynamic"):
        output = subprocess.run([str(ROOT / "build/release" / test)], capture_output=True, text=True, check=True, cwd=ROOT).stdout
        total += sum(int(n) for n in re.findall(r"(\d+) operations matched", output))
    return total


def main() -> int:
    quality = {"oracle_ops": oracle_operations()}
    coverage = read_json("results/quality/coverage.json")
    if coverage:
        quality["line_coverage"] = coverage["lines_percent"]
        quality["branch_coverage"] = coverage["branches_percent"]
    mutation = read_json("results/quality/mutation.json")
    if mutation:
        quality["mutation"] = {key: mutation[key] for key in ("killed", "scored", "score_percent", "equivalent")}
    fuzz = read_json("results/quality/fuzz.json")
    if fuzz:
        quality["fuzz"] = {key: fuzz[key] for key in ("ops", "traces", "rebuilds", "splits", "mismatches")}

    data = {"quality": quality}
    headline = read_json("results/headline.json")
    if headline:
        data["headline"] = headline
    body = json.dumps(data, indent=1)
    (ROOT / "site" / "results.js").write_text(f"// Generated by scripts/build_site_data.py. Do not edit.\nwindow.RESULTS = {body};\n")
    print(body[:400])
    return 0


if __name__ == "__main__":
    sys.exit(main())
