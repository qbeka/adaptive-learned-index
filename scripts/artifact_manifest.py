#!/usr/bin/env python3
"""Lists every recorded run with its commit, gate and a hash of its raw data.

Usage: scripts/artifact_manifest.py

Writes results/ARTIFACTS.md. A reader can hash a raw.jsonl and compare it here to
confirm that a number in the report came from this file.
"""
import hashlib
import json
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PURPOSE = {
    "update_validation": "Tuning sweep, picks one configuration per policy",
    "update_final": "Update throughput, quiet machine, the verdict",
    "update_latency": "Update latency, quiet machine",
    "update_final_loaded": "First throughput run, loaded machine, kept for comparison",
    "update_latency_loaded": "First latency run, loaded machine, kept for comparison",
    "update_memory": "Memory at allocator capacity",
    "update_work": "Work counters, instrumented binary, never timed",
    "update_same_epsilon": "Exploratory, same epsilon for both policies, decides nothing",
    "static_final": "Static lookups, full datasets",
    "static_warm": "Static lookups, data fits in cache",
}


def main() -> int:
    lines = ["# Artifact manifest", "",
             "Generated by `scripts/artifact_manifest.py`. Each run folder also holds a `manifest.json` "
             "with hardware, flags, baselines and input hashes.", "",
             "| Run | Purpose | Processes | Commit | Load gate | Median load | SHA-256 of raw.jsonl |",
             "|---|---|---|---|---|---|---|"]
    for name, purpose in PURPOSE.items():
        folder = ROOT / "results" / name
        manifest = json.loads((folder / "manifest.json").read_text())
        data = (folder / "raw.jsonl").read_bytes()
        records = [json.loads(line) for line in data.splitlines()]
        load = statistics.median(record["load_before"] for record in records)
        lines.append(f"| `{name}` | {purpose} | {len(records)} | `{manifest['commit'][:7]}` | "
                     f"{manifest['max_load']:g} | {load:.0f} | `{hashlib.sha256(data).hexdigest()[:16]}` |")
    (ROOT / "results/ARTIFACTS.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
